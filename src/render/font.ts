/** Packed glyph rows indexed by (charCode - 32) * 7 + row. */
const GLYPHS: Uint8Array = (() => {
  const out = new Uint8Array((LAST - FIRST + 1) * GLYPH_HEIGHT);
  for (let code = FIRST; code <= LAST; code++) {
    const rows = GLYPH_ROWS[String.fromCharCode(code)];
    if (!rows || rows.length !== GLYPH_HEIGHT) throw new Error(`font: missing glyph for code ${code}`);
    out.set(rows, (code - FIRST) * GLYPH_HEIGHT);
  }
  return out;
})();

const FALLBACK = '?'.charCodeAt(0);

/** The 7 row bitmasks of `ch` (bit 4 = leftmost column). Characters outside ASCII 32..126 render as "?". */
export function glyphRows(ch: string): Uint8Array {
  const code = ch.charCodeAt(0);
  const c = code >= FIRST && code <= LAST ? code : FALLBACK;
  return GLYPHS.subarray((c - FIRST) * GLYPH_HEIGHT, (c - FIRST + 1) * GLYPH_HEIGHT);
}

export interface TextOptions {
  /** Integer pixel magnification (default 1; fractions round down, invalid values fall back to 1). */
  scale?: number;
}

function textScale(opts: TextOptions | undefined): number {
  const s = Math.floor(opts?.scale ?? 1);
  return Number.isFinite(s) && s >= 1 ? s : 1;
}

/** Lines (split at LF, CRLF or CR) of code points; a non-ASCII character is one "?" cell when measuring and drawing. */
function lines(text: string): string[][] {
  return text.split(/\r\n|\r|\n/).map((l) => Array.from(l));
}

/**
 * Tight size of the rendered text: width = (longest line chars * 6 - 1) * scale,
 * height = (lines * 8 - 1) * scale. Empty text measures 0 x 0.
 */
export function measureText(text: string, opts?: TextOptions): { width: number; height: number } {
  if (text.length === 0) return { width: 0, height: 0 };
  const s = textScale(opts);
  const ls = lines(text);
  const cols = Math.max(...ls.map((l) => l.length));
  return { width: cols > 0 ? (cols * CELL_WIDTH - 1) * s : 0, height: (ls.length * CELL_HEIGHT - 1) * s };
}

/** Draw `text` with its top-left corner at (x, y) (rounded). "\n" starts a new line. */
export function drawText(
  img: ImageRGBA,
  x: number,
  y: number,
  text: string,
  color: ColorInput,
  opts?: TextOptions,
): void {
  const s = textScale(opts);
  const [r, g, b, a8] = toRGBA8(resolveColor(color));
  const a = a8 / 255;
  const ox = Math.round(x);
  let oy = Math.round(y);
  for (const line of lines(text)) {
    for (let ci = 0; ci < line.length; ci++) {
      const rows = glyphRows(line[ci]);
      const gx = ox + ci * CELL_WIDTH * s;
      for (let row = 0; row < GLYPH_HEIGHT; row++) {
        const bits = rows[row];
        if (bits === 0) continue;
        for (let col = 0; col < GLYPH_WIDTH; col++) {
          if (!(bits & (0x10 >> col))) continue;
          const px0 = gx + col * s;
          const py0 = oy + row * s;
          for (let py = Math.max(0, py0); py < Math.min(img.height, py0 + s); py++) {
            for (let px = Math.max(0, px0); px < Math.min(img.width, px0 + s); px++) {
              blendOver(img.data, (py * img.width + px) * 4, r, g, b, a);
            }
          }
        }
      }
    }
    oy += CELL_HEIGHT * s;
  }
}

export interface LabelOptions extends TextOptions {
  /** Text color (default white). */
  color?: ColorInput;
  /** Box color (default translucent near-black, readable over any background). */
  background?: ColorInput;
  /** Space between box edge and text in pixels (default 2 * scale). */
  padding?: number;
}

const LABEL_TEXT: RGBA = [1, 1, 1, 1];
const LABEL_BOX: RGBA = [0.05, 0.05, 0.07, 0.72];

/** Size of the box drawLabel would draw, as a rect at (x, y). */
export function measureLabel(text: string, x: number, y: number, opts?: LabelOptions): PixelRect {
  const pad = labelPadding(opts);
  const m = measureText(text, opts);
  return { x: Math.round(x), y: Math.round(y), width: m.width + 2 * pad, height: m.height + 2 * pad };
}

function labelPadding(opts: LabelOptions | undefined): number {
  const pad = opts?.padding;
  return pad !== undefined && Number.isFinite(pad) ? Math.max(0, Math.round(pad)) : 2 * textScale(opts);
}

/** Draw `text` on a translucent box whose top-left corner is (x, y). Returns the box rect. */
export function drawLabel(img: ImageRGBA, x: number, y: number, text: string, opts?: LabelOptions): PixelRect {
  const box = measureLabel(text, x, y, opts);
  const pad = labelPadding(opts);
  fillRect(img, box.x, box.y, box.width, box.height, opts?.background ?? LABEL_BOX);
  drawText(img, box.x + pad, box.y + pad, text, opts?.color ?? LABEL_TEXT, opts);
  return box;
}
